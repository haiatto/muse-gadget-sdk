#!/usr/bin/env python3
"""museStopWatch: split the Japanese caption font for the msw_font partition.

The firmware runs from PSRAM (CONFIG_SPIRAM_XIP_FROM_PSRAM), so the font's
glyph bitmaps (about 890 KB) would take that much PSRAM. This moves them to
a flash partition that the firmware maps in place (esp_partition_mmap).

In:  components/muse/fonts/muse_font_cjk_noto_jp_16.c (gen_cjk_noto_jp_font.sh)
Out: components/muse/fonts/muse_font_cjk_noto_jp_16.bin   (to the partition)
     components/muse/fonts/muse_font_cjk_noto_jp_16_part.c (the rest, built)

The .bin starts with a 16-byte header: "MSWF", version 1, the bitmap size and
its FNV-1a hash (all little-endian u32). The _part.c holds the same size and
hash, so a partition from another build of the font shows boxes, not garbage.

Run from esp32/: python tools/muse/split_cjk_noto_jp_font.py
"""
import re
import struct
import sys
from pathlib import Path

FONTS = Path("components/muse/fonts")
SRC = FONTS / "muse_font_cjk_noto_jp_16.c"
BIN = FONTS / "muse_font_cjk_noto_jp_16.bin"
PART = FONTS / "muse_font_cjk_noto_jp_16_part.c"


def fnv1a(data: bytes) -> int:
    h = 0x811C9DC5
    for b in data:
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    m = re.search(r"static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap\[\] = \{(.*?)\n\};\n", text, re.S)
    if not m:
        print("glyph_bitmap not found", file=sys.stderr)
        return 1
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    bitmap = bytes(int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body))
    h = fnv1a(bitmap)
    BIN.write_bytes(struct.pack("<4sIII", b"MSWF", 1, len(bitmap), h) + bitmap)

    rest = text[: m.start()] + text[m.end():]
    # The opts comment lists every character: keep only its first line.
    rest = re.sub(r"( \* Opts: [^\n]{0,200})[^\n]*", r"\1 ...", rest, count=1)
    rest = rest.replace("static const lv_font_fmt_txt_dsc_t font_dsc = {", "static lv_font_fmt_txt_dsc_t font_dsc = {", 1)
    rest = rest.replace("    .glyph_bitmap = glyph_bitmap,", "    .glyph_bitmap = NULL,   /* msw_font_get_glyph_dsc() maps it */", 1)
    rest = rest.replace("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,", "    .get_glyph_dsc = msw_font_get_glyph_dsc,", 1)
    head = f"""/* museStopWatch: generated by tools/muse/split_cjk_noto_jp_font.py from
 * muse_font_cjk_noto_jp_16.c. The glyph bitmaps are in the msw_font
 * partition (muse_font_cjk_noto_jp_16.bin), mapped in place on first use:
 * the firmware runs from PSRAM, and in the image they would take that much
 * PSRAM. Without the partition (an OTA that came before the USB write that
 * adds it), the characters show as boxes. Do not edit; run the script. */
#define MSW_FONT_BITMAP_SIZE {len(bitmap)}u
#define MSW_FONT_BITMAP_HASH 0x{h:08x}u
#include "muse_font_part.h"
"""
    marker = "#if MUSE_FONT_CJK_NOTO_JP_16\n"
    i = rest.index(marker) + len(marker)
    rest = rest[:i] + "\nMSW_FONT_PART_DEFINE(font_dsc)\n" + rest[i:]
    # MSW_FONT_PART_DEFINE needs font_dsc declared first.
    rest = rest.replace("#if MUSE_FONT_CJK_NOTO_JP_16\n\nMSW_FONT_PART_DEFINE(font_dsc)\n",
                        "#if MUSE_FONT_CJK_NOTO_JP_16\n\nstatic lv_font_fmt_txt_dsc_t font_dsc;\nMSW_FONT_PART_DEFINE(font_dsc)\n", 1)
    PART.write_text(head + rest, encoding="utf-8", newline="\n")
    print(f"{BIN}: {len(bitmap)} bytes of bitmaps, hash 0x{h:08x}; {PART}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
